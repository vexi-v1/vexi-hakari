export function resolveLanguage(search, saved) {
  const requested = new URLSearchParams(search).get('lang');
  const normalize = (value) => value === 'en' ? 'en' : ['zh', 'zh-TW', 'zh-Hant'].includes(value) ? 'zh-Hant' : null;
  return normalize(requested) || normalize(saved) || 'en';
}
export function translate(message, language, params = {}) {
  const template = language === 'zh-Hant' ? translations[message] ?? message : message;
  return template.replace(/\{(\w+)\}/g, (match, key) => params[key] === undefined ? match : String(params[key]));
}
